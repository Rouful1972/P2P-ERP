        elsif :new.actcode = :old.actcode then

            select journalno, balance
            into v_journalno, v_balance
            from pm_journaldl
            where ref_no = :new.ref_no;

            update pm_journaldl
            set dramount = nvl(:new.dramount,0), cramount = nvl(:new.cramount,0),
            balance = balance + (nvl(:new.dramount,0) - nvl(:old.dramount,0)) - (nvl(:new.cramount,0) - nvl(:old.cramount,0))
            where ref_no = :new.ref_no;

