CREATE OR REPLACE TRIGGER NPLWPPF.voucher
after insert on pm_voucher_item
for each row
declare

    v_parent                pm_accounts.parent%type;
    v_cash_parent            pm_accounts.parent%type;
    v_lvl                    pm_accounts.lvl%type;
    v_cash_lvl                pm_accounts.lvl%type;
    v_actname                pm_accounts.actname%type;
    v_cash_actname            pm_accounts.actname%type;
    v_vdate                    date;
    v_vtype                    pm_voucher.vtype%type;
    v_balance                pm_journaldl.balance%type:=0;
    v_cash_balance            pm_journaldl.balance%type:=0;
    v_count                    number(32);
    v_cash_actcode            pm_accounts.actcode%type;
    v_balance_count            number(32);
    v_balance_count_cash    number(32);
    v_max_journalno            number(32);
    v_voucher_count            number(32);
    v_max_cash_journalno    number(32);
    v_cash_ref_no            number(32);
    v_closing_date            date;
    v_opening_date            date;
    v_closed                char(3);
    v_superparent            varchar2(200);

begin
    -- for new head of accounts

    select startdate, enddate,closed
    into v_opening_date, v_closing_date, v_closed
    from finyear
    where curuse = 'YES';

    select parent, lvl, actname
    into v_parent, v_lvl, v_actname
    from pm_accounts
    where actcode = :new.actcode;

    select getSuperParent(v_actname)
    into v_superparent
    from dual;

    select vdate,vtype,actcode, cash_ref_no
    into v_vdate, v_vtype, v_cash_actcode, v_cash_ref_no
    from pm_voucher
    where voucherno = :new.voucherno;

    --- for Cash in hand

    select actname, parent, lvl
    into v_cash_actname, v_cash_parent, v_cash_lvl
    from pm_accounts
    where actcode = v_cash_actcode;

    select count(*)
    into v_balance_count
    from pm_journaldl
    where actcode = :new.actcode
    and vdate  <= v_vdate;

    select nvl(max(nvl(journalno,0)),0)
    into v_max_journalno
    from pm_journaldl
    where vdate <= v_vdate;

    update pm_journaldl set journalno = journalno + 2
    where journalno > v_max_journalno;

    if v_balance_count > 0 then

        select balance
        into v_balance
        from pm_journaldl
        where actcode = :new.actcode
        and journalno =
            (select max(journalno)
            from pm_journaldl
            where actcode = :new.actcode
            and vdate <= v_vdate);
    end if;

    ---- getting cash balance

    select count(*)
    into v_balance_count_cash
    from pm_journaldl
    where actcode = v_cash_actcode
    and vdate <= v_vdate;


    if v_balance_count_cash > 0 then

        select balance
        into v_cash_balance
        from pm_journaldl
        where actcode = v_cash_actcode
        and journalno =
            (select max(journalno)
            from pm_journaldl
            where actcode = v_cash_actcode
            and vdate <= v_vdate);
    end if;

    if v_vtype = 'ccv' then

        --- inserting for head of accounts

        if v_closed = 'NO' or (v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability'))then

            update pm_journaldl set balance = balance - :new.amount
            where journalno > v_max_journalno
            and actcode = :new.actcode;

        elsif v_closed = 'YES' and (v_superparent = 'Revenue' or v_superparent = 'Expense') then

            update pm_journaldl set balance = balance - :new.amount
            where journalno > v_max_journalno
            and actcode = :new.actcode
            and vdate <= v_closing_date;

        end if;

        insert into pm_journaldl(voucherno, vdate, actcode, actname, source,
        dramount, cramount, balance, journalno, ref_no)
        values ( :new.voucherno, v_vdate, :new.actcode, v_actname,'CCV',
        0, :new.amount, v_balance - :new.amount, v_max_journalno+1, :new.ref_no);

        ---- inserting for cash

        select count(*)
        into v_voucher_count
        from pm_journaldl
        where voucherno = :new.voucherno
        and actcode = v_cash_actcode;

        if v_voucher_count > 0 then

            update pm_journaldl set dramount = dramount + :new.amount,
            balance = balance + :new.amount
            where voucherno = :new.voucherno
            and actcode = v_cash_actcode;

            update pm_journaldl set balance = balance + :new.amount
            where journalno > (select journalno from pm_journaldl
                       where actcode = v_cash_actcode
                       and voucherno = :new.voucherno)
            and actcode = v_cash_actcode;

        else

            update pm_journaldl set balance = balance + :new.amount
            where journalno > v_max_journalno
            and actcode = v_cash_actcode;

            insert into pm_journaldl(voucherno, vdate, actcode, actname, source,
            dramount, cramount, balance, journalno, ref_no)
            values ( :new.voucherno, v_vdate, v_cash_actcode, v_cash_actname,'CCV',
            :new.amount, 0, v_cash_balance + :new.amount, v_max_journalno+2, v_cash_ref_no);

