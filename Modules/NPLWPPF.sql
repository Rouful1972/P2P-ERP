CREATE OR REPLACE TRIGGER NPLWPPF.journal_master_update
after update of vdate on pm_journal_voucher
for each row
declare

    CURSOR jv is select actcode,nvl(dramount,0),nvl(cramount,0), ref_no
            from pm_journal_jv
            where voucherno = :new.voucherno;

    jv_actcode        pm_accounts.actcode%type;
    jv_dramount        pm_journal_jv.dramount%type;
    jv_cramount        pm_journal_jv.cramount%type;
    jv_ref_no        pm_journal_jv.ref_no%type;
    v_parent        pm_accounts.parent%type;
    v_lvl            pm_accounts.lvl%type;
    v_actname        pm_accounts.actname%type;
    v_c                number(32);
    v_journalno        number(32);
    v_balance        number(32,2);
    v_closing_date        date;
    v_opening_date        date;
    v_closed            char(3);
    v_superparent        varchar2(200);


begin

    select startdate, enddate,closed
    into v_opening_date, v_closing_date, v_closed
    from finyear
    where curuse = 'YES';

    if :new.vdate <> :old.vdate then

        open jv;
        loop
        fetch jv into jv_actcode,jv_dramount,jv_cramount, jv_ref_no;
        exit when jv%notfound;

            select parent, lvl, actname
            into v_parent, v_lvl, v_actname
            from pm_accounts
            where actcode = jv_actcode;

            select getSuperParent(v_actname)
            into v_superparent
            from dual;

            if v_closed = 'NO' or (v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability'))then

                update pm_journaldl
                set balance = balance - jv_dramount + jv_cramount
                where actcode = jv_actcode
                and journalno > (select journalno from pm_journaldl where ref_no = jv_ref_no);

                delete from pm_journaldl
                where ref_no = jv_ref_no;

                select nvl(max(nvl(journalno,0)),0)
                into v_journalno
                from pm_journaldl
                where vdate <= :new.vdate;

                select count(*)
                into v_c
                from pm_journaldl
                where actcode = jv_actcode
                and vdate <= :new.vdate;

                if v_c > 0 then

                    select balance
                    into v_balance
                    from pm_journaldl
                    where actcode = jv_actcode
                    and journalno = (select max(journalno) from pm_journaldl where actcode = jv_actcode
                                        and vdate <= :new.vdate);

                else

                    v_balance := 0;

                end if;

                update pm_journaldl set balance = balance + jv_dramount - jv_cramount
                where journalno > v_journalno
                and actcode = jv_actcode;

                update pm_journaldl set journalno = journalno + 1
                where journalno > v_journalno;

                insert into pm_journaldl(voucherno, vdate, actcode, actname,
                dramount, cramount, balance, journalno, ref_no)
                values ( :new.voucherno, :new.vdate, jv_actcode, v_actname,
                jv_dramount, jv_cramount,v_balance + jv_dramount - jv_cramount,
                v_journalno+1, jv_ref_no);

                if v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability') then

                    dbms_output.put_line(v_opening_date||' to '||v_closing_date);
                    pfCalc(v_opening_date, v_closing_date);

                end if;

            elsif v_closed = 'YES' and (v_superparent = 'Revenue' or v_superparent = 'Expense') then

                update pm_journaldl
                set balance = balance - jv_dramount + jv_cramount
                where actcode = jv_actcode
                and journalno > (select journalno from pm_journaldl where ref_no = jv_ref_no)
                and vdate <= v_closing_date;

                delete from pm_journaldl
                where ref_no = jv_ref_no;

                select nvl(max(nvl(journalno,0)),0)
                into v_journalno
                from pm_journaldl
                where vdate <= :new.vdate;

                select count(*)
                into v_c
                from pm_journaldl
                where actcode = jv_actcode
                and vdate <= :new.vdate;

                if v_c > 0 then

                    select balance
                    into v_balance
                    from pm_journaldl
                    where actcode = jv_actcode
                    and journalno = (select max(journalno) from pm_journaldl where actcode = jv_actcode
                                        and vdate <= :new.vdate);

                else

                    v_balance := 0;

                end if;

                update pm_journaldl set balance = balance + jv_dramount - jv_cramount
                where journalno > v_journalno
                and actcode = jv_actcode
                and vdate <= v_closing_date;

                update pm_journaldl set journalno = journalno + 1
                where journalno > v_journalno;

                insert into pm_journaldl(voucherno, vdate, actcode, actname,
                dramount, cramount, balance, journalno, ref_no)
                values ( :new.voucherno, :new.vdate, jv_actcode, v_actname,
                jv_dramount, jv_cramount,v_balance + jv_dramount - jv_cramount,
                v_journalno+1, jv_ref_no);

            end if;

        end loop;
        close jv;

    end if;

end;
