CREATE OR REPLACE TRIGGER NPLWPPF.voucher_update
after update on pm_voucher_item
for each row
declare

    v_parent            pm_accounts.parent%type;
    v_cash_parent        pm_accounts.parent%type;
    v_lvl                pm_accounts.lvl%type;
    v_cash_lvl            pm_accounts.lvl%type;
    v_actname            pm_accounts.actname%type;
    v_cash_actname        pm_accounts.actname%type;
    v_vdate                date;
    v_vtype                pm_voucher.vtype%type;
    v_balance            pm_journaldl.balance%type:=0;
    v_cash_actcode        varchar2(200);
    v_cash_ref_no        number(32);
    v_c                    number(32);
    v_journalno            number(32);
    v_cash_journalno    number(32);
    v_closing_date        date;
    v_opening_date        date;
    v_closed            char(3);
    v_superparent        varchar2(200);
    v_oldactname        varchar2(200);
    v_oldsuperparent    varchar2(200);

begin

    select startdate, enddate,closed
    into v_opening_date, v_closing_date, v_closed
    from finyear
    where curuse = 'YES';

    select parent, lvl, actname
    into v_parent, v_lvl, v_actname
    from pm_accounts
    where actcode = :new.actcode;

    select actname
    into v_oldactname
    from pm_accounts
    where actcode = :old.actcode;

    select getSuperParent(v_actname)
    into v_superparent
    from dual;

    select getSuperParent(v_oldactname)
    into v_oldsuperparent
    from dual;

    select vdate,vtype, actcode, cash_ref_no
    into v_vdate, v_vtype, v_cash_actcode, v_cash_ref_no
    from pm_voucher
    where voucherno = :new.voucherno;

    select parent, lvl, actname
    into v_cash_parent, v_cash_lvl, v_cash_actname
    from pm_accounts
    where actcode = v_cash_actcode;

    dbms_output.put_line(v_vtype);

    if :new.actcode <> :old.actcode then

        if v_vtype = 'ccv' then

            if v_closed = 'NO' or (v_closed = 'YES' and (v_oldsuperparent = 'Asset' or v_oldsuperparent = 'Liability'))then

                update pm_journaldl
                set balance = balance + nvl(:old.amount,0)
                where actcode = :old.actcode
                and journalno > (select journalno from pm_journaldl where ref_no = :new.ref_no);

            elsif v_closed = 'YES' and (v_oldsuperparent = 'Revenue' or v_oldsuperparent = 'Expense') then

                update pm_journaldl
                set balance = balance + nvl(:old.amount,0)
                where actcode = :old.actcode
                and journalno > (select journalno from pm_journaldl where ref_no = :new.ref_no)
                and vdate <= v_closing_date;

            end if;

            delete from pm_journaldl where ref_no = :new.ref_no;

            select nvl(max(nvl(journalno,0)),0)
            into v_journalno
            from pm_journaldl
            where vdate <= v_vdate;

            select count(*)
            into v_c
            from pm_journaldl
            where actcode = :new.actcode
            and vdate <= v_vdate;

            if v_c > 0 then

                select balance
                into v_balance
                from pm_journaldl
                where actcode = :new.actcode
                and journalno = (select max(journalno) from pm_journaldl where actcode = :new.actcode
                                    and vdate <= v_vdate);

            else

                v_balance := 0;

            end if;

            if v_closed = 'NO' or (v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability'))then

                update pm_journaldl
                set balance = balance - nvl(:new.amount,0)
                where actcode = :new.actcode
                and journalno > v_journalno;

            elsif v_closed = 'YES' and (v_superparent = 'Revenue' or v_superparent = 'Expense') then

                update pm_journaldl
                set balance = balance - nvl(:new.amount,0)
                where actcode = :new.actcode
                and journalno > v_journalno
                and vdate <= v_closing_date;

            end if;

            update pm_journaldl set journalno = journalno + 1 where journalno > v_journalno;

            insert into pm_journaldl(voucherno, vdate, actcode, actname,
            dramount, cramount, balance, journalno, ref_no)
            values ( :new.voucherno, v_vdate, :new.actcode, v_actname,
            0, nvl(:new.amount,0),v_balance - nvl(:new.amount,0),
            v_journalno+1, :new.ref_no);

            select journalno
            into v_cash_journalno

            from pm_journaldl
            where ref_no = v_cash_ref_no;

            update pm_journaldl
            set dramount = dramount + nvl(:new.amount,0) - nvl(:old.amount,0),
            balance = balance + nvl(:new.amount,0) - nvl(:old.amount,0)
            where actcode = v_cash_actcode
            and journalno = v_cash_journalno;

            update pm_journaldl
            set balance = balance + nvl(:new.amount,0) - nvl(:old.amount,0)
            where actcode = v_cash_actcode
            and journalno > v_cash_journalno;

        elsif v_vtype = 'cdv' then

            if v_closed = 'NO' or (v_closed = 'YES' and (v_oldsuperparent = 'Asset' or v_oldsuperparent = 'Liability'))then

                update pm_journaldl
                set balance = balance - nvl(:old.amount,0)
                where actcode = :old.actcode
                and journalno > (select journalno from pm_journaldl where ref_no = :new.ref_no);

            elsif v_closed = 'YES' and (v_oldsuperparent = 'Revenue' or v_oldsuperparent = 'Expense') then

                update pm_journaldl
                set balance = balance - nvl(:old.amount,0)
                where actcode = :old.actcode
                and journalno > (select journalno from pm_journaldl where ref_no = :new.ref_no)
                and vdate <= v_closing_date;

            end if;

            delete from pm_journaldl where ref_no = :new.ref_no;

            select nvl(max(nvl(journalno,0)),0)
            into v_journalno
            from pm_journaldl
            where vdate <= v_vdate;

            select count(*)
            into v_c
            from pm_journaldl
            where actcode = :new.actcode
            and vdate <= v_vdate;

            if v_c > 0 then

                select balance
                into v_balance
                from pm_journaldl
                where actcode = :new.actcode
                and journalno = (select max(journalno) from pm_journaldl where actcode = :new.actcode
                                    and vdate <= v_vdate);

            else

                v_balance := 0;

            end if;

            if v_closed = 'NO' or (v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability'))then

                update pm_journaldl
                set balance = balance + nvl(:new.amount,0)
                where actcode = :new.actcode
                and journalno > v_journalno;

            elsif v_closed = 'YES' and (v_superparent = 'Revenue' or v_superparent = 'Expense') then

                update pm_journaldl
                set balance = balance + nvl(:new.amount,0)
                where actcode = :new.actcode
                and journalno > v_journalno
                and vdate <= v_closing_date;

            end if;

            update pm_journaldl set journalno = journalno + 1 where journalno > v_journalno;

            insert into pm_journaldl(voucherno, vdate, actcode, actname,
            dramount, cramount, balance, journalno, ref_no)
            values ( :new.voucherno, v_vdate, :new.actcode, v_actname,
            nvl(:new.amount,0),0,v_balance + nvl(:new.amount,0),
            v_journalno+1, :new.ref_no);

            select journalno
            into v_cash_journalno
            from pm_journaldl
            where ref_no = v_cash_ref_no;

            update pm_journaldl
            set cramount = cramount + nvl(:new.amount,0) - nvl(:old.amount,0),
            balance = balance - (nvl(:new.amount,0) - nvl(:old.amount,0))
            where actcode = v_cash_actcode
            and journalno = v_cash_journalno;

            update pm_journaldl
            set balance = balance - (nvl(:new.amount,0) - nvl(:old.amount,0))
            where actcode = v_cash_actcode
            and journalno > v_cash_journalno;

        end if;

    elsif :new.actcode = :old.actcode then

        if v_vtype = 'ccv' then

            update pm_journaldl
            set cramount = cramount + nvl(:new.amount,0) - nvl(:old.amount,0),
            balance = balance - (nvl(:new.amount,0) - nvl(:old.amount,0))
            where ref_no = :new.ref_no;

            if v_closed = 'NO' or (v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability'))then

                update pm_journaldl
                set balance = balance - (nvl(:new.amount,0) - nvl(:old.amount,0))
                where actcode = :new.actcode
                and journalno > (select journalno from pm_journaldl where ref_no = :new.ref_no);

            elsif v_closed = 'YES' and (v_superparent = 'Revenue' or v_superparent = 'Expense') then

                update pm_journaldl
                set balance = balance - (nvl(:new.amount,0) - nvl(:old.amount,0))
                where actcode = :new.actcode
                and journalno > (select journalno from pm_journaldl where ref_no = :new.ref_no)
                and vdate <= v_closing_date;

            end if;

            select journalno
            into v_cash_journalno
            from pm_journaldl
            where ref_no = v_cash_ref_no;

            update pm_journaldl
            set dramount = dramount + nvl(:new.amount,0) - nvl(:old.amount,0),
            balance = balance + nvl(:new.amount,0) - nvl(:old.amount,0)
            where actcode = v_cash_actcode
            and journalno = v_cash_journalno;

            update pm_journaldl
            set balance = balance + nvl(:new.amount,0) - nvl(:old.amount,0)
            where actcode = v_cash_actcode
            and journalno > v_cash_journalno;

        elsif v_vtype = 'cdv' then

            update pm_journaldl
            set dramount = dramount + nvl(:new.amount,0) - nvl(:old.amount,0),
            balance = balance + nvl(:new.amount,0) - nvl(:old.amount,0)
            where ref_no = :new.ref_no;

            if v_closed = 'NO' or (v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability'))then

                update pm_journaldl
                set balance = balance + nvl(:new.amount,0) - nvl(:old.amount,0)
                where actcode = :new.actcode
                and journalno > (select journalno from pm_journaldl where ref_no = :new.ref_no);

            elsif v_closed = 'YES' and (v_superparent = 'Revenue' or v_superparent = 'Expense') then

                update pm_journaldl
                set balance = balance + nvl(:new.amount,0) - nvl(:old.amount,0)
                where actcode = :new.actcode
                and journalno > (select journalno from pm_journaldl where ref_no = :new.ref_no)
                and vdate <= v_closing_date;

            end if;

            select journalno
            into v_cash_journalno
            from pm_journaldl
            where ref_no = v_cash_ref_no;

            update pm_journaldl
            set cramount = cramount + nvl(:new.amount,0) - nvl(:old.amount,0),
            balance = balance - (nvl(:new.amount,0) - nvl(:old.amount,0))
            where actcode = v_cash_actcode
            and journalno = v_cash_journalno;

            update pm_journaldl
            set balance = balance - (nvl(:new.amount,0) - nvl(:old.amount,0))
            where actcode = v_cash_actcode
            and journalno > v_cash_journalno;

        end if;

    end if;

    if v_closed = 'YES' then

        dbms_output.put_line(v_opening_date||' to '||v_closing_date);
        pfCalc(v_opening_date, v_closing_date);

    end if;


end;
