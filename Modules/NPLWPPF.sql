CREATE OR REPLACE TRIGGER NPLWPPF.journal_voucher
after insert on pm_journal_jv
for each row
declare

    v_parent            pm_accounts.parent%type;
    v_lvl                pm_accounts.lvl%type;
    v_actname            pm_accounts.actname%type;
    v_vdate                date;
    v_balance            pm_journaldl.balance%type:=0;
    v_count                number(32);
    v_balance_count        number(32);
    v_max_journalno        number(32);
    v_closing_date        date;
    v_opening_date        date;
    v_closed            char(3);
    v_superparent        varchar2(200);


begin
    -- for new head of accounts

    select startdate, enddate,closed
    into v_opening_date, v_closing_date, v_closed
    from finyear
    where curuse = 'YES';

    select parent, lvl, actname
    into v_parent, v_lvl, v_actname
    from pm_accounts
    where actcode = :new.actcode;

    select vdate
    into v_vdate
    from pm_journal_voucher
    where voucherno = :new.voucherno;

    select getSuperParent(v_actname)
    into v_superparent
    from dual;

    if v_closed = 'NO' or (v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability'))then

        select count(*)
        into v_balance_count
        from pm_journaldl
        where actcode = :new.actcode
        and vdate <= v_vdate;

        select nvl(max(nvl(journalno,0)),0)
        into v_max_journalno
        from pm_journaldl
        where vdate <= v_vdate;

        if v_balance_count > 0 then

            select balance
            into v_balance
            from pm_journaldl
            where actcode = :new.actcode
            and journalno =
                (select max(journalno)
                from pm_journaldl
                where actcode = :new.actcode
                and vdate <= v_vdate);
