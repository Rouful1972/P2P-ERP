            dbms_output.put_line(v_opening_date||' to '||v_closing_date);
            pfCalc(v_opening_date, v_closing_date);

        end if;

    elsif v_closed = 'YES' and (v_superparent = 'Revenue' or v_superparent = 'Expense') then

        select count(*)
        into v_balance_count
        from pm_journaldl
        where actcode = :new.actcode
        and vdate <= v_vdate;

        select nvl(max(nvl(journalno,0)),0)
        into v_max_journalno
        from pm_journaldl
        where vdate <= v_vdate;

        if v_balance_count > 0 then

            select balance
            into v_balance
            from pm_journaldl
            where actcode = :new.actcode
            and journalno =
                (select max(journalno)
                from pm_journaldl
                where actcode = :new.actcode
                and vdate <= v_vdate);
        end if;

        update pm_journaldl set balance = balance + nvl(:new.dramount,0) - nvl(:new.cramount,0)
        where journalno > v_max_journalno
        and actcode = :new.actcode
        and vdate <= v_closing_date;

        update pm_journaldl set journalno = journalno + 1
        where journalno > v_max_journalno;

        insert into pm_journaldl(voucherno, vdate, actcode, actname,
        dramount, cramount, balance, journalno, ref_no)
