    v_parent            pm_accounts.parent%type;
    v_lvl                pm_accounts.lvl%type;
    v_actname            pm_accounts.actname%type;
    v_vdate                date;
    v_journalno            number(32);
    v_c                    number(32);
    v_balance            number(32,2);
    v_closing_date        date;
    v_opening_date        date;
    v_closed            char(3);
    v_superparent        varchar2(200);
    v_oldactname        varchar2(200);
    v_oldsuperparent    varchar2(200);

begin

    select startdate, enddate,closed
    into v_opening_date, v_closing_date, v_closed
    from finyear
    where curuse = 'YES';

    select parent, lvl, actname
    into v_parent, v_lvl, v_actname
    from pm_accounts
    where actcode = :new.actcode;

    select vdate
    into v_vdate
    from pm_journal_voucher
    where voucherno = :new.voucherno;

    select getSuperParent(v_actname)
    into v_superparent
    from dual;

    select actname
    into v_oldactname
    from pm_accounts
    where actcode = :old.actcode;

    select getSuperParent(v_oldactname)
    into v_oldsuperparent
    from dual;

    if v_closed = 'NO' or (v_closed = 'YES' and (v_superparent = 'Asset' or v_superparent = 'Liability'))then

        if :new.actcode <> :old.actcode then

            select journalno
            into v_journalno
            from pm_journaldl
            where ref_no = :new.ref_no;

            delete from pm_journaldl where ref_no = :new.ref_no;

            if v_oldsuperparent = 'Revenue' or v_oldsuperparent ='Expense' then

                update pm_journaldl
                set balance = balance - nvl(:old.dramount,0) + nvl(:old.cramount,0)
                where actcode = :old.actcode
                and journalno > v_journalno
                and vdate <= v_closing_date;

            else

                update pm_journaldl
                set balance = balance - nvl(:old.dramount,0) + nvl(:old.cramount,0)
                where actcode = :old.actcode
                and journalno > v_journalno;

            end if;

            select nvl(max(nvl(journalno,0)),0)
            into v_journalno
            from pm_journaldl
            where vdate <= v_vdate;

            select count(*)
            into v_c
            from pm_journaldl
            where actcode = :new.actcode
            and vdate <= v_vdate;

            if v_c > 0 then

                select balance
                into v_balance
                from pm_journaldl
                where actcode = :new.actcode
                and journalno = (select max(journalno) from pm_journaldl where actcode = :new.actcode and
                                    vdate <= v_vdate);

            else

                v_balance := 0;

            end if;

            update pm_journaldl
            set balance = balance + nvl(:new.dramount,0) - nvl(:new.cramount,0)
            where actcode = :new.actcode
            and journalno > v_journalno;

            update pm_journaldl set journalno = journalno + 1 where journalno > v_journalno;

            insert into pm_journaldl(voucherno, vdate, actcode, actname,
            dramount, cramount, balance, journalno, ref_no)
            values ( :new.voucherno, v_vdate, :new.actcode, v_actname,
            nvl(:new.dramount,0), nvl(:new.cramount,0),
            v_balance + (nvl(:new.dramount,0)-nvl(:new.cramount,0)),
